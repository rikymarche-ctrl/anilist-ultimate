import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const files = [];
function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (/\.(ts|css|html)$/.test(path) && !/\.(test|spec)\.ts$/.test(path) && !/IconDefinitions\.ts$/.test(path)) files.push(path);
  }
}
walk('src');
const metadata = JSON.parse(readFileSync('node_modules/@fortawesome/fontawesome-free/metadata/icon-families.json', 'utf8'));
const icons = new Set(Object.keys(metadata));
const classes = new Set(files.flatMap(path => [...readFileSync(path, 'utf8').matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)].map(match => match[1])));
const utilities = /^(?:solid|regular|brands|light|thin|duotone|classic|sharp|fw|spin(?:-.+)?|pulse|beat(?:-fade)?|fade|bounce|shake|flip(?:-.+)?|rotate(?:-.+)?|stack(?:-.+)?|border|pull-.+|inverse|layers(?:-.+)?|size|xs|sm|lg|xl|2xl|\d+x)$/;
const missing = [...classes].filter(name => !icons.has(name) && !utilities.test(name));
if (missing.length) throw new Error(`Unresolved icon classes: ${missing.join(', ')}`);
const names = [...classes].filter(name => icons.has(name)).sort();
const definitions = names.flatMap(name => {
  const data = metadata[name];
  return data.familyStylesByLicense.free.filter(style => style.family === 'classic').map(({ style }) => {
    const svg = data.svgs.classic[style];
    return { prefix: { solid: 'fas', regular: 'far', brands: 'fab' }[style], iconName: name,
      icon: [svg.width, svg.height, [], data.unicode, svg.path] };
  });
});
const output = '// Generated by scripts/generate-icons.mjs from Font Awesome Free metadata.\n'
  + '// Icons: CC BY 4.0; see https://fontawesome.com/license/free\n'
  + 'export const iconDefinitions = ' + JSON.stringify(definitions) + ';\n';
const target = 'src/core/ui/IconDefinitions.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Icon inventory changed; run node scripts/generate-icons.mjs');
} else writeFileSync(target, output);
console.log(`Icons: ${names.length} names, ${definitions.length} variants, ${Buffer.byteLength(output)} source bytes`);
